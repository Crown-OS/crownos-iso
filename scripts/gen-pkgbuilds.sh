#!/usr/bin/env bash
# Generates the PKGBUILDs crownos-source users build from: one per release entry
# of components.toml, at its pinned tag and sibling commits, with the version of
# the asset the binary repository ships.
#
#   gen-pkgbuilds.sh REPO_DIR OUT_DIR
#
# REPO_DIR is a resolved repository (scripts/manifest.sh resolve). An entry with
# a pkgbuild path builds from that file at its tag; any other entry gets the
# generic Rust template, which installs the binaries the asset ships. Entries
# whose workspace needs siblings that are not pinned yet are skipped. OUT_DIR is
# the Crown-OS/crownos-pkgbuilds checkout: directories of packages no longer
# generated are removed.

set -euo pipefail
shopt -s nullglob

root=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
# shellcheck source=scripts/lib.sh
source "$root/scripts/lib.sh"
require_tools gh jq python3 bsdtar makepkg

usage='usage: gen-pkgbuilds.sh REPO_DIR OUT_DIR'
repo_dir=$(realpath -- "${1:?$usage}")
mkdir -p -- "${2:?$usage}"
out_dir=$(realpath -- "$2")
work=$(mktemp -d)
trap 'rm -rf -- "$work"' EXIT

warn() { printf 'warning: %s\n' "$*" >&2; }

quoted_list() {
    local item
    for item; do printf " '%s'" "$item"; done
}

# Maps each sibling checkout directory to its repository, from a three-column
# siblings.lock on the release when there is one, else from the alias table.
sibling_repos() {
    local repo=$1 tag=$2 dir repository commit
    declare -gA repo_of_dir=()
    while read -r dir repository commit; do
        if [[ -n $commit && $dir != '#'* ]]; then repo_of_dir[$dir]=${repository##*/}; fi
    done < <(gh release download "$tag" --repo "$repo" --pattern siblings.lock --output - 2>/dev/null || true)
}

sibling_sources() {
    local siblings=$1 dir commit
    while read -r dir commit; do
        printf '"%s::git+https://github.com/Crown-OS/%s.git#commit=%s"\n' \
            "$dir" "${repo_of_dir[$dir]:-$(sibling_repo "$dir")}" "$commit"
    done < <(jq -r 'to_entries[] | "\(.key) \(.value)"' <<<"$siblings")
}

has_cargo_lock() {
    gh api "repos/$1/contents/Cargo.lock?ref=$2" --silent 2>/dev/null
}

write_generic() {
    local entry=$1 dir=$2 repo tag asset siblings checkout file version
    read -r repo tag asset < <(jq -r '[.repo, .tag, .asset] | join(" ")' <<<"$entry")
    siblings=$(jq -c '.siblings' <<<"$entry")
    checkout=${repo##*/} file=$repo_dir/$asset
    version=$(package_version "$file")
    local -a sources bins depends licenses
    mapfile -t sources < <(printf '"%s::git+https://github.com/%s.git#tag=%s"\n' "$checkout" "$repo" "$tag"; sibling_sources "$siblings")
    mapfile -t bins < <(bsdtar -tf "$file" | while read -r path; do
        [[ $path == usr/bin/?* && $path != */ ]] && printf '%s\n' "${path#usr/bin/}"
    done)
    mapfile -t depends < <(package_field "$file" depend)
    mapfile -t licenses < <(package_field "$file" license)
    local description locked='' frozen=''
    description=$(package_field "$file" pkgdesc | tr -d "'")
    description=${description:-"${checkout} for CrownOS"}
    if has_cargo_lock "$repo" "$tag"; then locked=' --locked' frozen=' --frozen'; fi

    cat >"$dir/PKGBUILD" <<PKGBUILD
# Generated by crownos-iso/scripts/gen-pkgbuilds.sh from components.toml; do not edit.
pkgname=$(jq -r .name <<<"$entry")
pkgver=${version%-*}
pkgrel=${version##*-}
pkgdesc='$description'
arch=(x86_64)
url='https://github.com/$repo'
license=($(quoted_list "${licenses[@]}") )
depends=($(quoted_list "${depends[@]}") )
makedepends=('cargo' 'git' 'clang')
options=(!debug)
source=(${sources[*]})
sha256sums=($(printf " 'SKIP'%.0s" "${sources[@]}") )

prepare() {
  cd "\$srcdir/$checkout"
  export RUSTUP_TOOLCHAIN=stable
  cargo fetch$locked --target "\$(rustc -vV | sed -n 's/^host: //p')"
}

build() {
  cd "\$srcdir/$checkout"
  export RUSTUP_TOOLCHAIN=stable CARGO_TARGET_DIR=target
  cargo build$frozen --release --bins
}

package() {
  cd "\$srcdir/$checkout"
  install -Dm755 -t "\$pkgdir/usr/bin"$(printf ' target/release/%s' "${bins[@]}")
}
PKGBUILD
}

# Copies the PKGBUILD directory from the release tag and points a PKGBUILD that
# builds its own checkout ($startdir/..) at a pinned clone instead.
write_from_repo() {
    local entry=$1 dir=$2 repo tag pkgbuild siblings source_dir checkout version file
    read -r repo tag pkgbuild < <(jq -r '[.repo, .tag, .pkgbuild] | join(" ")' <<<"$entry")
    siblings=$(jq -c '.siblings' <<<"$entry")
    source_dir=${pkgbuild%/*} checkout=${repo##*/}
    version=$(package_version "$repo_dir/$(jq -r .asset <<<"$entry")")
    while read -r file; do
        gh api -H 'Accept: application/vnd.github.raw' "repos/$repo/contents/$source_dir/$file?ref=$tag" >"$dir/$file"
    done < <(gh api "repos/$repo/contents/$source_dir?ref=$tag" --jq '.[] | select(.type == "file") | .name')
    [[ $pkgbuild == */PKGBUILD && -e $dir/PKGBUILD ]] || die "$repo $tag has no $pkgbuild"

    local line builds_checkout='' rewritten=()
    while IFS= read -r line; do
        case $line in
            pkgver=*) line=pkgver=${version%-*} ;;
            pkgrel=*) line=pkgrel=${version##*-} ;;
            "_workspace=\"\$startdir/..\"")
                builds_checkout=1
                line="_workspace=\"\$srcdir/$checkout\""
                ;;
        esac
        rewritten+=("$line")
    done <"$dir/PKGBUILD"
    if [[ -n $builds_checkout ]]; then
        if [[ $siblings == null ]]; then
            warn "skipping $repo: its workspace siblings are not pinned (no siblings.lock on $tag)"
            return 0
        fi
        local -a sources
        mapfile -t sources < <(printf '"%s::git+https://github.com/%s.git#tag=%s"\n' "$checkout" "$repo" "$tag"; sibling_sources "$siblings")
        rewritten+=("" "source=(${sources[*]})" "sha256sums=($(printf " 'SKIP'%.0s" "${sources[@]}") )")
    fi
    {
        echo '# Generated by crownos-iso/scripts/gen-pkgbuilds.sh from components.toml; do not edit.'
        printf '%s\n' "${rewritten[@]}"
    } >"$dir/PKGBUILD"
    ready=1
}

generate() {
    local entry=$1 name repo tag dir ready=''
    read -r name repo tag < <(jq -r '[.name, .repo, .tag] | join(" ")' <<<"$entry")
    dir=$work/$name
    mkdir -p -- "$dir"
    sibling_repos "$repo" "$tag"
    if jq -e 'has("pkgbuild")' >/dev/null <<<"$entry"; then
        write_from_repo "$entry" "$dir"
    elif jq -e 'has("siblings")' >/dev/null <<<"$entry"; then
        write_generic "$entry" "$dir"
        ready=1
    else
        warn "skipping $name: its siblings are not pinned (no siblings.lock on $repo $tag)"
    fi
    [[ -n $ready ]] || return 0
    (cd -- "$dir" && makepkg --printsrcinfo >.SRCINFO)
    rm -rf -- "${out_dir:?}/$name"
    mv -- "$dir" "$out_dir/$name"
    generated+=("$name")
}

write_readme() {
    cat >"$out_dir/README.md" <<'README'
# crownos-pkgbuilds

Generated by `crownos-iso/scripts/gen-pkgbuilds.sh` from `crownos-iso/components.toml`
whenever an ISO tag is promoted to stable. Do not edit: changes are overwritten.

`crownos-source` adds this repository to paru as `[crownos-src]`, so `paru -Syu`
rebuilds each CrownOS component from the same tag and sibling commits as the
binary package in `[crownos]`, tuned with `-march=native` / `-C target-cpu=native`.
A component missing here has no pinned siblings yet and stays on its binary package.
README
}

generated=()
while read -r entry; do
    generate "$entry"
done < <(manifest_json | jq -c '.package[] | select(.repo)')

for stale in "$out_dir"/*/; do
    stale=${stale%/}
    [[ " ${generated[*]} " == *" ${stale##*/} "* ]] || rm -rf -- "$stale"
done
write_readme
printf 'generated %s\n' "${generated[*]}"
